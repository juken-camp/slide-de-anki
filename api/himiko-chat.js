function sameSiteRequest(req) {
  const origin = header(req, 'origin');
  if (!origin) return header(req, 'sec-fetch-site') !== 'cross-site';
  try {
    const url = new URL(origin);
    if (!['https:', 'http:'].includes(url.protocol) || url.origin !== origin) return false;
    // Host routing is supplied by the deployment; do not trust a client-provided
    // x-forwarded-host as a separate allowlist. This is CSRF defense, not login.
    if (url.host === header(req, 'host')) return true;
    const allowed = (process.env.HIMIKO_ALLOWED_ORIGINS || '').split(',').map(x => x.trim()).filter(Boolean);
    return allowed.includes(origin);
  } catch { return false; }
}

