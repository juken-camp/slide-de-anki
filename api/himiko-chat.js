function rateBuckets(req, now = Date.now()) {
  // On Vercel use the platform's client-address header. On other deployments,
  // use the socket peer unless the operator explicitly trusts its reverse proxy.
  let ip = process.env.VERCEL ? (header(req, 'x-vercel-forwarded-for') || header(req, 'x-forwarded-for')).split(',')[0].trim() : '';
  if (!ip && process.env.HIMIKO_TRUST_PROXY === '1') ip = header(req, 'x-forwarded-for').split(',')[0].trim();
  if (!ip) ip = req.socket?.remoteAddress || 'unknown';
  const digest = createHash('sha256').update((process.env.HIMIKO_RATE_LIMIT_SALT || 'himiko-chat') + ':' + ip).digest('hex');
  const minute = Math.floor(now / 60000);
  const day = Math.floor((now + 9 * 3600000) / 86400000); // Japan calendar day.
  const seconds = Math.max(1, Math.ceil(((day + 1) * 86400000 - 9 * 3600000 - now) / 1000));
  const perMinute = setting('HIMIKO_REQUESTS_PER_MINUTE', 60, 1, 1000);
  const perDay = setting('HIMIKO_REQUESTS_PER_DAY', 600, 1, 100000);
  const globalDay = setting('HIMIKO_TOTAL_REQUESTS_PER_DAY', 5000, 1, 1000000);
  return [
    { key: `hc:{himiko-chat}:m:${minute}:${digest}`, cap: perMinute, ttl: 61 },
    { key: `hc:{himiko-chat}:d:${day}:${digest}`, cap: perDay, ttl: seconds },
    { key: `hc:{himiko-chat}:total:${day}`, cap: globalDay, ttl: seconds }
  ];
}

function localRateLimit(buckets, now = Date.now()) {
  for (const [key, record] of localCounters) if (record.expires <= now) localCounters.delete(key);
  for (let i = 0; i < buckets.length; i++) {
    const b = buckets[i], record = localCounters.get(b.key);
    if (record && record.count >= b.cap) return { ok: false, retryAfter: Math.max(1, Math.ceil((record.expires - now) / 1000)), bucket: i + 1 };
  }
  if (localCounters.size + buckets.filter(b => !localCounters.has(b.key)).length > 20000) return { ok: false, retryAfter: 60, bucket: 1 };
  for (const b of buckets) {
    const existing = localCounters.get(b.key);
    if (existing) existing.count++;
    else localCounters.set(b.key, { count: 1, expires: now + b.ttl * 1000 });
  }
  return { ok: true, retryAfter: 0, bucket: 0 };
}

async function rateLimit(req) {
  const buckets = rateBuckets(req);
  const url = process.env.UPSTASH_REDIS_REST_URL || process.env.KV_REST_API_URL;
  const token = process.env.UPSTASH_REDIS_REST_TOKEN || process.env.KV_REST_API_TOKEN;
  if (!url && !token) {
    if (process.env.HIMIKO_REQUIRE_SHARED_RATE_LIMIT === '1') throw Object.assign(new Error('ただいま利用制限の設定を確認中です。しばらくしてからお試しください。'), { status: 503 });
    // Best effort only: serverless restarts/parallel instances do not share this map.
    return localRateLimit(buckets);
  }
  if (!url || !token || !/^https:\/\//.test(url)) throw new Error('rate-limit configuration');
  const controller = new AbortController();
  const timer = setTimeout(() => controller.abort(), 3000);
  try {
    const response = await fetch(url.replace(/\/$/, ''), {
      method: 'POST', signal: controller.signal,
      headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' },
      body: JSON.stringify(['EVAL', RATE_SCRIPT, '3', ...buckets.map(b => b.key), ...buckets.map(b => String(b.cap)), ...buckets.map(b => String(b.ttl))])
    });
    if (!response.ok) throw new Error('rate-limit service');
    const data = await response.json();
    if (data.error || !Array.isArray(data.result) || data.result.length < 3 || !data.result.every(Number.isFinite) || ![0, 1].includes(data.result[0])) throw new Error('rate-limit response');
    return { ok: data.result[0] === 1, retryAfter: Math.max(1, Math.ceil(data.result[1])), bucket: data.result[2] };
  } finally { clearTimeout(timer); }
}

